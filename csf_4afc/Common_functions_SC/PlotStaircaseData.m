%% Fitting the curve on the data and plotting the CSF
%Just for the graphs and curve fitting
[Frequency,freqIdx] = sort(Freq);
[Size,sizeidx] = sort(Gabor.SCShuffle);

% Get data from RawData and put it into a matrix
for d = 1:length(RawData)
    DataTmp(d,1) = RawData(d).SC;
    DataTmp(d,2) = RawData(d).SF;
    DataTmp(d,3) = RawData(d).CstThr; 
end

ContThr = [];
for sz = 1:length(sizeidx)
    tmpSize = DataTmp(:,1) == Gabor.SpacialConstant_Deg(sizeidx(sz));
    DataToPlot = [];
    DataToPlot = DataTmp(tmpSize,2:3,:);
    for f = 1:length(freqIdx)
        ContThr(sz,f) = DataToPlot(freqIdx(f),2);
    end
    
    ContSen = [];
    ContSen = 1./(ContThr(sz,:));
    
    % Fit generated by cftool
    figure;
    [fitresult, gof] = createFit(Frequency, ContSen);
    title(['Sigma: ' num2str(round(Gabor.SpacialConstant_Deg(sizeidx(sz)),0)) 'deg, CSF (healthy)'])
    plotName = sprintf('%s/%s_%s_%s_%s',FolderName,Parameters.Subj_ID,num2str(Parameters.Subj_DOB),...
        num2str(TIMESTAMP),['CSF_Function_Sigma' num2str(round(Gabor.SpacialConstant_Deg(sizeidx(sz)),0)) 'deg']);
    saveas(gcf,plotName,'png')
end
